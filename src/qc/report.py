def f(v, d=3):
    return "—" if v is None else f"{v:.{d}f}"


def pct(v):
    return "—" if v is None else f"{100 * v:.1f} %"


def headline_table(ev) -> str:
    rows = ["| Pipeline (detector + segmenter) | Decision accuracy | Decision macro F1 | Scrap escapes "
            "(SCRAP→PASS) | False scrap (PASS→SCRAP) | Missed devices | Latency / frame (CPU) |",
            "|---|---|---|---|---|---|---|"]
    for s in ev["segmenters"]:
        e = ev["end_to_end"][s]
        rows.append(f"| YOLO11n + {NAMES[s]} | {f(e['decision_accuracy'])} | {f(e['decision_macro_f1'])} | "
                    f"{pct(e['scrap_escape_rate'])} | {pct(e['false_scrap_rate'])} | {e['missed_devices']} / "
                    f"{e['gt_devices']} | {e['latency_ms_per_frame']['mean']:.0f} ms |")
    return "\n".join(rows)


def iou_table(ev) -> str:
    segs = ev["segmenters"]
    rows = ["| Defect | " + " | ".join(f"{NAMES[s]} IoU | {NAMES[s]} Dice" for s in segs) + " |",
            "|---|" + "---|---|" * len(segs)]
    for c in C.DEFECT_CLASSES:
        rows.append(f"| {c} | " + " | ".join(
            f"{f(ev['pixel'][s]['per_class'][c]['IoU'])} | {f(ev['pixel'][s]['per_class'][c]['Dice'])}"
            for s in segs) + " |")
    rows.append("| **mean** | " + " | ".join(
        f"**{f(ev['pixel'][s]['mean_IoU'])}** | **{f(ev['pixel'][s]['mean_Dice'])}**" for s in segs) + " |")
    return "\n".join(rows)


def type_table(ev) -> str:
    segs = ev["segmenters"]
    rows = ["| Significant defect type | Devices | " + " | ".join(
        f"{NAMES[s]} recall | {NAMES[s]} precision" for s in segs) + " |", "|---|---|" + "---|---|" * len(segs)]
    for c in C.DEFECT_CLASSES:
        t0 = ev["end_to_end"][segs[0]]["defect_type_recognition"][c]
        rows.append(f"| {c} | {t0['support']} | " + " | ".join(
            f"{f(ev['end_to_end'][s]['defect_type_recognition'][c]['recall'])} | "
            f"{f(ev['end_to_end'][s]['defect_type_recognition'][c]['precision'])}" for s in segs) + " |")
    return "\n".join(rows)


def confusion_md(e) -> str:
    cm = e["confusion_matrix"]
    rows = ["| True \\ Predicted | " + " | ".join(cm["labels_pred"]) + " |",
            "|---|" + "---|" * len(cm["labels_pred"])]
    for lab, row in zip(cm["labels_true"], cm["matrix"]):
        rows.append(f"| **{lab}** | " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(rows)


